test('overlapping cleanup spans count their union and failed cleanup remains a failure', () => {
    const spans = [[0, 1100, 'pass'], [500, 1500, 'pass'], [1100, 1800, 'fail'], [1800, 2100, 'pass']].map(([start, end, status], i) => ({ bucket: 'teardown', source: i === 2 ? 'test-services' : 'target', label: `cleanup-${i}`, start_time: instant(start), end_time: instant(end), duration_ms: end - start, status }));
    const collation = { bucket: 'report_collation', source: 'target', start_time: instant(2100), end_time: instant(2120), duration_ms: 20, status: 'pass' };
    const result = calculateTargetTiming('sample', [], 'fail', collation, spans, instant(2200));
    assert.equal(result.accountableWindow.wallDurationMs, 2100);
    assert.equal(result.timing.generated_at, instant(2200));
    const bucket = result.timing.buckets.find(b => b.name === 'teardown');
    assert.equal(bucket.duration_ms, 2100);
    assert.equal(bucket.spans.length, 4);
    assert.deepEqual(result.timing.slowest_lifecycle_bucket, { name: 'teardown', duration_ms: 2100 });
    const failures = timingFailuresFromSpans(spans);
    assert.equal(failures.length, 1);
    assert.equal(failures[0].label, 'cleanup-2');
    assert.equal(teardownStatus(2100, failures), 'fail');
});
test('shared execution is grouped separately from target accounting', () => {
    const records = [0, 1000].map((start, i) => ({ execution_group: 'backend', shared_report: `shard-${i}`, status: 'pass', start_time: instant(start), end_time: instant(start + 2000), wall_duration_ms: 2000, executed_duration_ms: 2000 }));
    const [group] = groupSharedExecutionRecords(records);
    assert.equal(group.wall_duration_ms, 3000);
    assert.equal(group.executed_duration_ms, 4000);
    assert.equal(group.reports, 2);
    assert.deepEqual(group.shared_reports, ['shard-0', 'shard-1']);
    assert.equal(group.status, 'pass');
    assert.equal(groupSharedExecutionRecords([{ ...records[0], status: 'fail' }])[0].failure_class, 'harness');
});
const activity = (duration, name, overrides = {}) => ({ service: 'postgres', target: 'fixture', operation: 'transaction', strategy: 'template-clone', reuse_scope: 'transaction', fixture_policy: 'transaction', fixture_class: 'transaction', caller_package: 'internal/modules/auth', test_name: name, duration_ms: duration, ...overrides });
test('fixture thresholds, tie order, hotspot cap and parent projections preserve exact work', () => {
    const summary = summarizeFixtureActivityList('fixture', [activity(20000, 'TestSlowB'), activity(15000, 'TestSlowA'), activity(1000, 'TestClone', { caller_package: 'internal/modules/entities', operation: 'database-create', reuse_scope: 'per-test', fixture_policy: 'template_clone' })]);
    assert.equal(summary.total_count, 3);
    assert.equal(summary.total_duration_ms, 36000);
    assert.equal(fixtureSummaryLine(summary, { thresholdMs: 40000 }), '');
    const line = fixtureSummaryLine(summary, { thresholdMs: 30000, top: 2 });
    assert.match(line, /total=36\.0s count=3/);
    assert.match(line, /slowest=TestSlowB\(20\.0s\),TestSlowA\(15\.0s\)/);
    const tie = summarizeFixtureActivityList('fixture', [activity(10000, 'A', { fixture_class: 'reset' }), activity(10000, 'B', { fixture_class: 'reset' }), activity(20000, 'C')]);
    assert.deepEqual(tie.by_strategy.map(x => [x.fixture_class, x.count, x.total_duration_ms]), [['reset', 2, 20000], ['transaction', 1, 20000]]);
    const cap = summarizeFixtureActivityList('fixture', [4, 3, 2, 1].map((n) => activity(n * 1000, `Test${n}`, { caller_package: `pkg/${n}` })));
    const capped = fixtureSummaryLine(cap, { thresholdMs: 1, top: 4 });
    assert.match(capped, /pkg\/4/);
    assert.match(capped, /pkg\/2/);
    assert.doesNotMatch(capped, /pkg\/1/);
    const combined = combineFixtureSummaries('parent', emptyFixtureSummary('parent'), [{ target: 'fixture', fixture: summary }]);
    assert.equal(combined.total_duration_ms, 36000);
    assert.equal(combined.total_count, 3);
});
