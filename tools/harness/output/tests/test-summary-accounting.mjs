test('step accounting separates counted, reused, derived and diagnostic observations', () => {
    const observations = [stepSummary(), stepSummary({ label: 'reused', accounting_mode: 'reused', executed_duration_ms: 0, wall_duration_ms: 0, logical_duration_ms: 2000, counting_mode: 'none', owners: ['sample'] }), stepSummary({ label: 'derived', accounting_mode: 'derived', executed_duration_ms: 0, wall_duration_ms: 0, logical_duration_ms: 3000, counting_mode: 'none' })];
    const before = structuredClone(observations);
    const summary = summarizeTargetSteps('sample', observations);
    assert.deepEqual(observations, before);
    assert.equal(summary.counts.tests, 7);
    assert.equal(summary.counts.support, 7);
    assert.equal(summary.counts.packages, 1);
    assert.equal(summary.counts.steps, 3);
    assert.deepEqual(summary.accountingModes, { actual: 1, reused: 1, derived: 1 });
    assert.equal(summary.executedDurationMs, 1000);
    assert.equal(summary.logicalDurationMs, 6000);
    assert.equal(summary.reusedDurationMs, 2000);
    assert.equal(summary.derivedDurationMs, 3000);
    assert.equal(summary.wallDurationMs, 1000);
});
test('richer failures replace wrapper duplicates without losing the actual failure', () => {
    const generic = { source: 'shell', runner: 'shell', label: '(shell command)', failure_class: 'harness', failure_reason: 'unknown_failure', message: 'command exited with status 1' };
    const rich = { failure_class: 'security', failure_reason: 'security_finding', message: 'reachable vulnerability' };
    const observation = stepSummary({ status: 'fail', counts: { failed: 2, non_test: 2, non_test_failed: 2 }, failures: [generic, rich] });
    const summary = summarizeTargetSteps('sample', [observation]);
    assert.equal(summary.failed, true);
    assert.deepEqual(summary.failures, [rich]);
    assert.equal(summary.counts.failed, 1);
    assert.equal(summary.counts.non_test_failed, 1);
    assert.equal(observation.failures.length, 2);
    assert.deepEqual(summarizeTargetSteps('sample', [stepSummary({ status: 'fail', failures: [generic] })]).failures, [generic]);
});
test('child and run totals count the child union once and preserve independent windows', () => {
    const a = targetSummary('child-a', { tests: 7, steps: 2, executed: 1000, logical: 1200 });
    const b = targetSummary('child-b', { tests: 11, steps: 3, executed: 2000 });
    const children = combineSummarySections('parent', [a, b]);
    assert.equal(children.counts.tests, 18);
    assert.equal(children.counts.steps, 5);
    assert.equal(children.executed_duration_ms, 3000);
    assert.equal(children.logical_duration_ms, 3200);
    assert.equal(children.wall_duration_ms, 1000);
    const own = targetSummary('parent', { tests: 0, steps: 1, executed: 100, logical: 100 });
    const totals = combineSummarySections('parent', [own, children]);
    const run = summarizeTargetSummaries([{ ...own, own, totals }], []);
    assert.equal(run.aggregate.tests, 18);
    assert.equal(run.aggregate.steps, 6);
    assert.equal(run.aggregate.executed_duration_ms, 3100);
    assert.equal(run.aggregate.logical_duration_ms, 3300);
    assert.equal(run.wallDurationMs, 1000);
    assert.deepEqual(run.accountingModes, { actual: 6, reused: 0, derived: 0 });
    assert.equal(run.failed, false);
    assert.equal(findSlowestTarget([a, { ...b, critical_path_wall_duration_ms: 2000 }]).target, 'child-b');
});
