import {readFileSync, mkdirSync, writeFileSync} from 'node:fs';
import {spawnSync} from 'node:child_process';

// Recovery's canonical machine catalog is the complete relation set. Generated
// executable SQL stays inside the ordinary backend scan, and inside any provider
// dependency closure that attempts to import this maintenance capability.
const catalog=JSON.parse(readFileSync('contracts/recovery/fixtures/recovery-state-catalog.v3.json','utf8'));
const tables=[...catalog.tables].sort((a,b)=>a.table_name.localeCompare(b.table_name));
if(catalog.schema_id!=='cartulary.recovery_state_catalog.v3' || tables.some(table=>!/^\w+$/.test(table.table_name)) || new Set(tables.map(t=>t.table_name)).size!==tables.length) throw new Error('invalid maintenance relation catalog');
const ownership=JSON.parse(readFileSync('tools/schema_object_ownership_manifest.json','utf8'));
if(ownership.goose_ledger!=='public.goose_db_version') throw new Error('unqualified migration ledger');
const readable=[...tables,{table_name:'goose_db_version'}].sort((a,b)=>a.table_name.localeCompare(b.table_name));
const mutable=tables.filter(t=>t.backup_inclusion!=='excluded_schema_metadata' && t.table_name!=='recovery_target_state');
const restored=tables.filter(t=>t.restore_action==='restore');
const quote=JSON.stringify;
const relation=t=>`"public"."${t.table_name}"`;
let output=`// Code generated by generate-maintenance-sql.mjs from the Recovery catalog. DO NOT EDIT.
package maintenancequery

import (
 "fmt"
 "github.com/JochiRaider/cartulary/internal/platform/sqlshape"
)

// From admits only current catalog relations; callers compose read-only clauses.
func From(table string) (sqlshape.Fragment,error) {
 switch table {
${readable.map(t=>`case ${quote(t.table_name)}: return sqlshape.Literal(${quote('FROM '+relation(t))}),nil`).join('\n')}
 default: return sqlshape.Fragment{},fmt.Errorf("unadmitted maintenance relation %q",table)
 }
}
`;
for(const [name,selection,template] of [
 ['Delete',mutable,t=>`DELETE FROM ${relation(t)}`],
 ['LockShare',tables.filter(t=>t.table_name==='recovery_target_state'),t=>`LOCK TABLE ${relation(t)} IN SHARE MODE`],
]) output+=`
func ${name}(table string) (sqlshape.Statement,error) {
 switch table {
 ${selection.map(t=>`case ${quote(t.table_name)}: return sqlshape.Command(${quote(template(t))}),nil`).join('\n')}
 default:return sqlshape.Statement{},fmt.Errorf("unadmitted ${name} relation %q",table)
 }
}
`;
for(const [name,selection,prefix,suffix] of [
 ['TruncateRestore',tables.filter(t=>['restore','rebuild','invalidate'].includes(t.restore_action)),'TRUNCATE ',' CASCADE'],
 ['TruncateVerification',mutable,'TRUNCATE ',' CASCADE'],
 ['LockMutable',mutable,'LOCK TABLE ',' IN ACCESS EXCLUSIVE MODE'],
]) output+=`
func ${name}(tables []string) (sqlshape.Statement,error) {
 if !sameTables(tables,[]string{${selection.map(t=>quote(t.table_name)).join(',')}}) {return sqlshape.Statement{},fmt.Errorf("unadmitted ${name} relation set")}
 return sqlshape.Command(${quote(prefix+selection.map(relation).join(', ')+suffix)}),nil
}
`;
output+=`
// Insert excludes generated columns and optionally verifies their recomputation.
func Insert(table string,columns sqlshape.Fragment,generated bool) (sqlshape.Statement,error) {
 switch table {
 ${restored.map(t=>{
 const base=`INSERT INTO ${relation(t)} (%s) SELECT %s FROM jsonb_populate_record(NULL::${relation(t)}, $1::jsonb)`;
 return `case ${quote(t.table_name)}:
 if generated {return sqlshape.Command(${quote(`WITH restored AS (${base} RETURNING *) SELECT (to_jsonb(restored)-$2::text[]) IS NOT DISTINCT FROM ($1::jsonb-$2::text[]) FROM restored`)},columns,columns),nil}
 return sqlshape.Command(${quote(base)},columns,columns),nil`;
 }).join('\n')}
 default:return sqlshape.Statement{},fmt.Errorf("unadmitted restore relation %q",table)
 }
}
`;
mkdirSync('internal/platform/maintenancequery',{recursive:true});
writeFileSync('internal/platform/maintenancequery/catalog_generated.go',output);

const formatted=spawnSync(process.env.GO,['fmt','./internal/platform/maintenancequery'],{stdio:'pipe',encoding:'utf8'});
if(formatted.status!==0 || formatted.error) throw new Error(formatted.stderr || formatted.error?.message || 'format maintenance SQL failed');
