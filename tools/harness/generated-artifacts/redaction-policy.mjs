// The native redactor carries the complete authored policy in its executable.
// It must never substitute a smaller runtime fallback if the checkout moves.
export function renderNativeRedactionPolicy(manifest) {
  if (manifest?.schema_id !== "cartulary.harness_redaction_manifest.v1" ||
      typeof manifest.replacement !== "string" || !manifest.replacement ||
      !Array.isArray(manifest.value_patterns) || !manifest.value_patterns.length) {
    throw new Error("invalid native redaction policy");
  }
  const names = new Set();
  const rules = manifest.value_patterns.map((rule) => {
    if (!rule || typeof rule.name !== "string" || !rule.name || names.has(rule.name) ||
        typeof rule.pattern !== "string" || !rule.pattern ||
        typeof rule.replacement !== "string" || !rule.replacement) {
      throw new Error("invalid or duplicate native redaction rule");
    }
    names.add(rule.name);
    // Validate the shared consumer syntax before the publication transaction.
    // Go's regexp compiler independently admits the generated native projection.
    new RegExp(rule.pattern.replace(/^\(\?i\)/u, ""), "giu");
    return `\t\t{pattern: regexp.MustCompile(${JSON.stringify(rule.pattern)}), replacement: ${JSON.stringify(rule.replacement)}},`;
  });
  return `// Code generated by tools/harness/generated-artifacts/generate-foundation-schema-validators.mjs; DO NOT EDIT.
package harnessredact

import "regexp"

var rules = compiledManifest{
\treplacement: ${JSON.stringify(manifest.replacement)},
\tvalueRules: []compiledRule{
${rules.join("\n")}
\t},
}
`;
}
