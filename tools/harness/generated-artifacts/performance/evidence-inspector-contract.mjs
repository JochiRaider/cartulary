import { createHash } from "node:crypto";
import { readFileSync } from "node:fs";
import path from "node:path";

import { parseStrictJSON, validateSchemaSync } from "../../contract/index.mjs";

export function validateEvidenceInspectorCapabilities(contract, viewSchema, policy) {
  const filter = viewSchema.fields.find((field) => field.field_key === contract.workload.filter_field_key);
  if (viewSchema.view_schema_id !== contract.view_schema_id || filter?.read_kind !== "boolean" ||
    !filter.filter_ops.includes(contract.workload.filter_operator)) {
    throw new Error("Evidence inspector preparation exceeds admitted view capabilities");
  }
  if (contract.measurement_policy_id !== policy.policy_id ||
    ["warmup_passes", "measured_samples", "percentile", "estimator", "product_retries"].some((key) => contract[key] !== policy[key])) {
    throw new Error("Evidence inspector sampling differs from its measurement policy");
  }
  const fixture = contract.fixture;
  if (fixture.object_count !== fixture.evidence_rows || fixture.object_count * fixture.object_bytes !== fixture.total_object_bytes ||
    fixture.linked_evidence_count !== contract.workload.preview_preflight_records) {
    throw new Error("Evidence inspector physical population or preview qualification diverged");
  }
}

export function renderEvidenceInspectorContract(root) {
  const inputs = [
    ["contracts/performance/ac045.v2.json", "cartulary.performance_evidence_inspector_contract.v1"],
    ["contracts/view-schemas/cartulary.view.timeline.v2.json", "cartulary.view_schema_source.v1"],
    ["tools/measurement_policy_owner.json", "cartulary.measurement_policy.v1"],
  ].map(([relative, schemaID]) => {
    const bytes = readFileSync(path.join(root, relative));
    const value = parseStrictJSON(new TextDecoder("utf-8", { fatal: true }).decode(bytes), relative);
    validateSchemaSync(schemaID, value);
    return { bytes, value };
  });
  const [contract, viewSchema, policy] = inputs.map((input) => input.value);
  validateEvidenceInspectorCapabilities(contract, viewSchema, policy);
  const digest = createHash("sha256");
  for (const input of inputs) digest.update(input.bytes);
  return [
    "// Code generated by cartulary.evidence_inspector_contract_generation.v1; DO NOT EDIT.",
    `// Input SHA-256: ${digest.digest("hex")}`,
    "",
    `export const cartularyEvidenceInspectorContract = ${JSON.stringify(contract, null, 2)} as const;`,
    "",
  ].join("\n");
}
