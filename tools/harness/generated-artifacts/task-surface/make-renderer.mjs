export function taskSurfaceMakeDensity(manifest) {
  const bindings = renderTaskSurfaceMake(manifest);
  const runtime = renderTaskSurfaceMakeRuntime(manifest);
  const syntheticManifest = structuredClone(manifest);
  for (let index = 1; index <= 25; index += 1) {
    const target = `synthetic-step-target-${String(index).padStart(2, "0")}`;
    syntheticManifest.targets.push({
      name: target,
      target_class: "internal_helper",
      default_inclusion_sets: ["helper_only"],
      lifecycle_state: "candidate_child",
    });
    syntheticManifest.make_recipes[target] = {
      prerequisites: ["frontend-install"],
      type: "readiness_projection",
    };
  }
  const syntheticBindings = renderTaskSurfaceMake(syntheticManifest);
  return {
    bindings_bytes: Buffer.byteLength(bindings),
    runtime_bytes: Buffer.byteLength(runtime),
    combined_bytes: Buffer.byteLength(bindings) + Buffer.byteLength(runtime),
    maximum_line_bytes: Math.max(maximumLineBytes(bindings), maximumLineBytes(runtime)),
    repeated_origin_transport_count: bindings.split(
      ["CARTULARY_MAKE", "ORIGIN", ""].join("_"),
    ).length - 1,
    repeated_input_value_expansion_count: (bindings.match(/\$\([A-Z][A-Z0-9_]+\)/g) ?? []).length,
    synthetic_target_count: 25,
    synthetic_average_growth_bytes:
      (Buffer.byteLength(syntheticBindings) - Buffer.byteLength(bindings)) / 25,
  };
}

export function collectTaskSurfaceMakeDensityErrors(manifest) {
  const metrics = taskSurfaceMakeDensity(manifest);
  const errors = [];
  for (const [metric, budget] of [
    ["bindings_bytes", generatedMakeBudgets.bindingsBytes],
    ["runtime_bytes", generatedMakeBudgets.runtimeBytes],
    ["combined_bytes", generatedMakeBudgets.combinedBytes],
    ["maximum_line_bytes", generatedMakeBudgets.maximumLineBytes],
    ["synthetic_average_growth_bytes", generatedMakeBudgets.averageTargetGrowthBytes],
  ]) {
    if (metrics[metric] > budget) {
      errors.push(`generated Make density ${metric}=${metrics[metric]} exceeds budget ${budget}`);
    }
  }
  if (metrics.repeated_origin_transport_count !== 0) {
    errors.push("generated Make bindings must not contain per-variable origin transport");
  }
  return errors;
}

function maximumLineBytes(content) {
  return Math.max(...content.split("\n").map((line) => Buffer.byteLength(line)));
}

function sequenceProducedSummaryTargets(manifest) {
  const produced = new Set();
  for (const sequence of Object.values(manifest.sequences ?? {})) {
    for (const step of sequence.steps ?? []) {
      for (const target of step.produces_summary_targets ?? []) {
        produced.add(target);
      }
    }
  }
  return produced;
}

function sequenceStepTargets(manifest) {
  const targets = new Set();
  for (const sequence of Object.values(manifest.sequences ?? {})) {
    for (const step of sequence.steps ?? []) {
      targets.add(step.target);
    }
  }
  return targets;
}

function shouldEmitRetainedTargetSummary(recipe, entry, manifest) {
  if (entry?.output_policy?.summary_schema !== "cartulary.tool_run_summary.v5") {
    return false;
  }
  return sequenceProducedSummaryTargets(manifest).has(recipe.target);
}

function renderMakeRecipe(recipe, manifest) {
  if (recipe.graph_entry === true) {
    const childRecipe = { ...recipe };
    delete childRecipe.graph_entry;
    const graphRecipe = {
      target: recipe.target,
      prerequisites: ["$(NODE_BIN)"],
      type: "work_graph",
      selection: "target",
      test_target: recipe.test_target,
      exports: recipe.exports,
      comments: recipe.comments,
    };
    return [
      "ifeq ($(CARTULARY_HARNESS_GRAPH_CHILD),1)",
      ...renderMakeRecipe(childRecipe, manifest),
      "else",
      ...renderMakeRecipe(graphRecipe, manifest),
      "endif",
    ];
  }
  const entry = targetEntryMap(manifest).get(recipe.target);
  const nodeReadinessPrelude = renderNodeReadinessPrelude(recipe, entry);
  const prerequisitePrelude = renderPrerequisitePrelude(
    recipe,
    entry,
    manifest,
    {
      excludeNodeRuntime: nodeReadinessPrelude.length > 0,
    },
  );
  const preflightPrelude = renderPreflightPrelude(recipe, entry, manifest);
  const publicPrelude = [...nodeReadinessPrelude, ...preflightPrelude];
  const prerequisites =
    nodeReadinessPrelude.length > 0 || prerequisitePrelude.length > 0
      ? ""
      : (recipe.prerequisites ?? []).join(" ");
  const header = prerequisites
    ? `${recipe.target}: ${prerequisites}`
    : `${recipe.target}:`;
  const prefix = renderRecipePrefix(recipe, entry);
  if (["artifact_binding", "aggregate", "readiness_projection"].includes(recipe.type)) {
    const lines = [...prefix, header, ...publicPrelude, ...prerequisitePrelude];
    if (entry?.output_policy?.summary_schema === "cartulary.tool_run_summary.v5") {
      lines.push(`\t$(call RUN_TARGET_SUMMARY,${recipe.target},pass)`);
    }
    return lines;
  }
  if (recipe.type === "cleanup") {
    if (recipe.scope === "distclean") {
      return [
        ...prefix,
        header,
        ...publicPrelude,
        "\t$(Q)$(RUN_HARNESS_CLEANUP) distclean $(DISTCLEAN_PATHS)",
      ];
    }
    return [
      ...prefix,
      header,
      ...publicPrelude,
      "\t$(Q)$(RUN_HARNESS_CLEANUP) clean $(CLEAN_PATHS)",
    ];
  }
  if (recipe.type === "print_help") {
    const variable =
      recipe.scope === "all"
        ? "TASK_SURFACE_HELP_ALL_LINES"
        : "TASK_SURFACE_HELP_LINES";
    return [
      ...prefix,
      header,
      ...publicPrelude,
      `\t$(Q)printf '%s\\n' $(${variable})`,
    ];
  }
  if (recipe.type === "work_graph") {
    const forwarded = runtimeForwardedInputEnvEntries(entry);
    const selectionArgs =
      recipe.selection === "owner"
        ? `--selection owner --target ${recipe.target} --owner "$(OWNER)" $(if $(strip $(ROWS)),--rows "$(ROWS)",)${recipe.service_backed_only === true ? " --service-backed-only" : ""}`
        : `--selection ${recipe.selection} --target ${recipe.target}`;
    return [
      ...prefix,
      header,
      ...publicPrelude,
      ...prerequisitePrelude,
      `\t$(Q)env ${envStripArgsForTarget(entry, manifest)} $(TASK_SURFACE_MACHINE_STATE_ENV) ${forwarded.join(" ")} MAKE="$(MAKE)" NODE_BIN="$(NODE_BIN)" TEST_SERVICES_BIN="$(TEST_SERVICES_BIN)" $(NODE_BIN) ./tools/harness/scheduler/work-graph/runner-cli.mjs ${selectionArgs}`,
    ];
  }
  if (recipe.type === "step_command") {
    const emitsRetainedTargetSummary =
      recipe.mode === "run_step" &&
      shouldEmitRetainedTargetSummary(recipe, entry, manifest);
    const lines = [
      ...prefix,
      header,
      ...publicPrelude,
      ...prerequisitePrelude,
      ...renderStepCommandRecipe(recipe, entry, manifest),
    ];
    if (recipe.success_summary === true && !emitsRetainedTargetSummary) {
      lines.push(`\t$(call RUN_TARGET_SUMMARY,${recipe.target},pass)`);
    }
    return lines;
  }
  if (recipe.type === "summary_target") {
    const status = recipe.status ?? "pass";
    const stepLabel =
      recipe.step_label ?? `${recipe.target} child ${recipe.child_target}`;
    const projection = recipe.projection
      ? ` --projection ${recipe.projection}`
      : "";
    const env = [
      'MAKE_BIN="$(MAKE)"',
      'NODE_BIN="$(NODE_BIN)"',
      'TEST_OUTPUT_SCRIPT="$(TEST_OUTPUT_SCRIPT)"',
      'TASK_SURFACE_MANIFEST="$(TASK_SURFACE_CANONICAL_TASK_SURFACE_MANIFEST)"',
      'RUN_STEP_SCRIPT="$(RUN_STEP_SCRIPT)"',
    ];
    return [
      ...prefix,
      header,
      ...publicPrelude,
      ...prerequisitePrelude,
      `\t$(Q)env ${envStripArgsForTarget(entry, manifest)} ${env.join(" ")} $(NODE_BIN) $(CARTULARY_RUNNER_SCRIPT) summary-target --target ${recipe.target} --child-target ${recipe.child_target} --status ${status} --step-label "${stepLabel}"${projection}`,
    ];
  }
  if (recipe.type === "node_tool" || recipe.type === "owner_command") {
    const env = uniqueValues([
      ...inputEntriesForTarget(entry),
      ...makeNodeToolResultDirMakeEnvVars(recipe.target),
      ...makeNodeToolRuntimeEnvVars(recipe.target),
    ])
      .map((name) => `${name}="${makeVariableValue(name)}"`)
      .join(" ");
    return [
      ...prefix,
      header,
      ...publicPrelude,
      ...prerequisitePrelude,
      `\t$(Q)$(call RUN_MAKE_NODE_TOOL,${recipe.target},${env})`,
    ];
  }
  throw new Error(`unsupported Make recipe type ${recipe.type}`);
}

function shouldCentralizePrerequisiteOutput(
  recipe,
  entry = null,
  manifest = null,
) {
  return (
    (entry?.target_class === "public" ||
      sequenceStepTargets(manifest).has(recipe.target)) &&
    (recipe.prerequisites ?? []).length > 0 &&
    !["cleanup", "print_help"].includes(recipe.type)
  );
}

function renderPreflightPrelude(recipe, entry = null, manifest = null) {
  if (entry?.target_class !== "public") {
    return [];
  }
  if (recipe.target === "bootstrap-node-runtime") {
    return [];
  }
  return [`\t$(Q)$(call RUN_PUBLIC_PREFLIGHT,${recipe.target})`];
}

function renderNodeReadinessPrelude(recipe, entry = null) {
  if (
    entry?.target_class !== "public" ||
    recipe.target === "bootstrap-node-runtime"
  ) {
    return [];
  }
  return [
    '\t$(Q)if [ "$${CARTULARY_HARNESS_SKIP_PREREQUISITES:-0}" != "1" ]; then env -u CARTULARY_TEST_TARGET CARTULARY_SUPPRESS_CHILD_SUCCESS=1 $(MAKE) --silent --no-print-directory $(NODE_BIN); fi',
  ];
}

function renderPrerequisitePrelude(
  recipe,
  entry = null,
  manifest = null,
  { excludeNodeRuntime = false } = {},
) {
  if (!shouldCentralizePrerequisiteOutput(recipe, entry, manifest)) {
    return [];
  }
  const prerequisites = (recipe.prerequisites ?? []).filter(
    (prerequisite) => !(excludeNodeRuntime && prerequisite === "$(NODE_BIN)"),
  );
  if (prerequisites.length === 0) {
    return [];
  }
  const jobOption =
    recipe.prerequisite_jobs === undefined
      ? ""
      : `--jobs=${recipe.prerequisite_jobs}`;
  const condition =
    recipe.type === "artifact_binding"
      ? '[ "$${CARTULARY_HARNESS_GRAPH_ARTIFACT_CHILD:-0}" = "1" ] || [ "$${CARTULARY_HARNESS_SKIP_PREREQUISITES:-0}" != "1" ]'
      : '[ "$${CARTULARY_HARNESS_SKIP_PREREQUISITES:-0}" != "1" ]';
  return [
    `\t$(Q)if ${condition}; then env -u CARTULARY_TEST_TARGET CARTULARY_SUPPRESS_CHILD_SUCCESS=1 $(MAKE) --silent --no-print-directory ` +
      `${jobOption}${jobOption.length > 0 ? " " : ""}${prerequisites.join(" ")}; fi`,
  ];
}

function renderRecipePrefix(recipe, entry = null) {
  const lines = [];
  for (const comment of recipe.comments ?? []) {
    lines.push(`# ${comment}`);
  }
  if (
    entry?.target_class === "public" &&
    entry.output_policy?.artifact_policy !== "none" &&
    recipe.exports?.CARTULARY_TEST_RUN_ID === undefined
  ) {
    lines.push(
      `${recipe.target}: export CARTULARY_TEST_RUN_ID := $(CARTULARY_TEST_RUN_ID)`,
    );
  }
  if (recipe.test_target === "self") {
    lines.push(
      `${recipe.target}: export CARTULARY_TEST_TARGET ?= ${recipe.target}`,
    );
  }
  if (entry?.target_class !== "public") {
    lines.push(
      `${recipe.target}: export CARTULARY_SUPPRESS_CHILD_SUCCESS ?= 1`,
    );
  }
  for (const [name, value] of Object.entries(recipe.exports ?? {})) {
    lines.push(`${recipe.target}: export ${name} := ${value}`);
  }
  return lines;
}

function publicMakeInputNames(manifest) {
  const names = new Set([
    ...restrictedInternalMakeVariables,
    ...nonCanonicalPublicMakeVariables,
    ...retiredPublicMakeVariables,
    ...globalInputEntries(manifest).map((input) => input.name),
  ]);
  for (const entry of targetEntries(manifest ?? { targets: [] })) {
    if (entry.target_class !== "public") {
      continue;
    }
    for (const input of entry.input_contract?.inputs ?? []) {
      names.add(input.name);
    }
  }
  return Array.from(names).sort((left, right) => left.localeCompare(right));
}

function inputEntriesForTarget(entry = null) {
  return (entry?.input_contract?.inputs ?? []).map((input) => input.name);
}

function uniqueValues(values) {
  return Array.from(new Set(values));
}

function makeVariableValue(name) {
  return canonicalInternalMakeValues[name] ?? `$(${name})`;
}

function normalizeInternalMakeReferences(value) {
  if (typeof value !== "string") {
    return value;
  }
  let normalized = value;
  for (const [name, replacement] of Object.entries(canonicalInternalMakeValues)) {
    normalized = normalized.replaceAll(`$(${name})`, replacement);
  }
  return normalized;
}

function runtimeForwardedInputNames(entry = null) {
  return new Set(
    (entry?.input_contract?.inputs ?? [])
      .filter((input) =>
        ["runtime_env", "argv_and_runtime_env"].includes(input.child_forwarding),
      )
      .map((input) => input.name),
  );
}

function runtimeForwardedInputEnvEntries(entry = null) {
  const names = [...runtimeForwardedInputNames(entry)].sort((left, right) =>
    left.localeCompare(right),
  );
  return [
    ...names.map((name) => `${name}="$(${name})"`),
    ...(names.length > 0
      ? [
          `CARTULARY_MAKE_INPUT_SOURCES="$(call TASK_SURFACE_INPUT_SOURCES,${names.join(" ")})"`,
        ]
      : []),
  ];
}

function envStripArgsForTarget() {
  return "$(TASK_SURFACE_PUBLIC_INPUT_STRIP_ENV)";
}

function envCommandPrefixForTarget(entry = null, manifest = null, env = []) {
  return [
    "env",
    envStripArgsForTarget(entry, manifest),
    "$(TASK_SURFACE_MACHINE_STATE_ENV)",
    ...env,
  ]
    .filter((part) => part && part.trim() !== "")
    .join(" ");
}

function renderStepCommandRecipe(recipe, entry = null, manifest = null) {
  const forwardedEnv = runtimeForwardedInputEnvEntries(entry);
  const env = [
    ...forwardedEnv,
    ...Object.entries(recipe.env ?? {}).map(
      ([name, value]) => `${name}="${normalizeInternalMakeReferences(value)}"`,
    ),
  ];
  const envPrefix = `${envCommandPrefixForTarget(entry, manifest, env)} `;
  const args = (recipe.args ?? []).map(normalizeInternalMakeReferences).join(" ");
  const argsSuffix = args ? ` ${args}` : "";
  const command = (recipe.command ?? []).map(normalizeInternalMakeReferences).join(" ");
  if (recipe.mode === "run_step") {
    const runnerEnv = [...forwardedEnv];
    if (recipe.success_summary === true) {
      runnerEnv.push("CARTULARY_SUPPRESS_CHILD_SUCCESS=1");
    }
    if (recipe.failure_note) {
      runnerEnv.push(`CARTULARY_STEP_FAILURE_NOTE="${recipe.failure_note}"`);
    }
    const runnerPrefix = runnerEnv.length > 0 ? `${runnerEnv.join(" ")} ` : "";
    const childPrefix = `${envCommandPrefixForTarget(entry, manifest, env)} `;
    if (shouldEmitRetainedTargetSummary(recipe, entry, manifest)) {
      return [
        `\t$(Q)${runnerPrefix}$(RUN_STEP_SCRIPT) "${recipe.step_label}" -- ${childPrefix}${command}${argsSuffix}; status=$$?; if [ "$$status" -eq 0 ]; then $(call RUN_RETAINED_TARGET_SUMMARY,${recipe.target},pass); summary_status=$$?; else $(call RUN_RETAINED_TARGET_SUMMARY,${recipe.target},fail); summary_status=$$?; fi; if [ "$$summary_status" -ne 0 ]; then exit "$$summary_status"; fi; exit "$$status"`,
      ];
    }
    return [
      `\t$(Q)${runnerPrefix}$(RUN_STEP_SCRIPT) "${recipe.step_label}" -- ${childPrefix}${command}${argsSuffix}`,
    ];
  }
  if (recipe.mode === "node") {
    return [`\t$(Q)${envPrefix}$(NODE_BIN) ${normalizeInternalMakeReferences(recipe.script)}${argsSuffix}`];
  }
  if (recipe.mode === "command") {
    if (entry?.output_policy?.summary_schema === "cartulary.tool_run_summary.v5") {
      const childPrefix = `${envCommandPrefixForTarget(entry, manifest, env)} `;
      const testTarget = `CARTULARY_TEST_TARGET="$\${CARTULARY_TEST_TARGET:-${recipe.target}}"`;
      return [
        `\t$(Q)${testTarget} $(RUN_STEP_SCRIPT) "${recipe.target}" -- ${childPrefix}${command}${argsSuffix}`,
      ];
    }
    return [`\t$(Q)${envPrefix}${command}${argsSuffix}`];
  }
  throw new Error(`unsupported step command mode ${recipe.mode}`);
}

export function helpLines(manifest) {
  const lines = ["Cartulary compact workflow task surface", ""];
  appendHelpTierLines(lines, {
    name: "compact",
    entries: compactHelpEntries(manifest),
  });
  lines.push("");
  lines.push("For all public targets, run: make help-all");
  lines.push(
    "For private/check internals, run: make task-surface-report TASK_SURFACE_REPORT_ARGS=--all",
  );
  return trimTrailingBlank(lines);
}

export function helpAllLines(manifest) {
  const lines = ["Cartulary public task surface", ""];
  lines.push("How to read task evidence:");
  lines.push("  target -> owner partition -> semantic row -> artifact");
  lines.push(
    "  public evidence is runnable from this surface; support/internal evidence is shown by task-guide and explain-*.",
  );
  lines.push("");
  for (const tier of helpTiers(manifest)) {
    appendHelpTierLines(lines, tier);
    lines.push("");
  }
  return trimTrailingBlank(lines);
}

function appendHelpTierLines(lines, tier) {
  if (!tier) {
    return;
  }
  lines.push(`${tier.name}:`);
  for (const entry of tier.entries) {
    lines.push(...renderHelpEntryLines(entry));
  }
}

function renderHelpEntryLines(entry) {
  const command = `make ${entry.target}`;
  const description = entry.description.trim();
  const usage = typeof entry.usage === "string" ? entry.usage.trim() : "";
  if (!usage && entry.target.length <= helpTargetColumnWidth) {
    return [
      `  make ${entry.target.padEnd(helpTargetColumnWidth)} ${description}`,
    ];
  }
  const detail = usage ? `${usage} ${description}` : description;
  return [`  ${command}`, `${helpDescriptionIndent}${detail}`];
}

function trimTrailingBlank(lines) {
  if (lines[lines.length - 1] === "") {
    lines.pop();
  }
  return lines;
}

function escapeMakeSingleQuoted(value) {
  return value.replaceAll("'", "'\"'\"'");
}

function wrapPhysicalLines(lines, maxLength = 500) {
  const wrapped = [];
  for (const line of lines) {
    let remaining = line;
    const continuation = line.startsWith("\t") ? "\t  " : "  ";
    while (remaining.length > maxLength) {
      let split = remaining.lastIndexOf(" ", maxLength - 2);
      if (split <= 0) {
        split = remaining.indexOf(" ", maxLength - 2);
      }
      if (split <= 0) {
        break;
      }
      wrapped.push(`${remaining.slice(0, split)} \\`);
      remaining = `${continuation}${remaining.slice(split + 1)}`;
    }
    wrapped.push(remaining);
  }
  return wrapped;
}
