const helpTargetColumnWidth = 30;
const helpDescriptionIndent = " ".repeat(
  2 + "make ".length + helpTargetColumnWidth + 1,
);
const generatedMakeBudgets = Object.freeze({
  bindingsBytes: 180 * 1024,
  runtimeBytes: 64 * 1024,
  combinedBytes: 220 * 1024,
  maximumLineBytes: 512,
  averageTargetGrowthBytes: 512,
});

// Producer context for rendering: each registered binding's producer ID and
// default path (P5-3), read from this checkout's registry unless a caller
// supplies it, so every rendering of the same checkout agrees.
const repositoryRoot = new URL("../../../../", import.meta.url).pathname;
let repositoryProducers;
function checkoutProducers() {
  repositoryProducers ??= producerContext(repositoryRoot);
  return repositoryProducers;
}

export function renderTaskSurfaceMake(manifest) {
  const lines = [
    "# Code generated by tools/harness/generated-artifacts/render-task-surface-make.mjs; DO NOT EDIT.",
    "",
  ];
  const nativeRecipes = makeRecipeEntries(manifest).filter((recipe) => recipe.type === "native_tool");
  lines.push(`ifneq ($(filter ${nativeRecipes.map((recipe) => recipe.target).join(" ")},$(MAKECMDGOALS)),)`);
  lines.push(`.PHONY: ${nativeRecipes.map((recipe) => recipe.target).join(" ")}`);
  for (const recipe of nativeRecipes) lines.push(...renderMakeRecipe(recipe, manifest), "");
  lines.push("else");
  const targets = targetEntries(manifest);
  lines.push(".PHONY: \\");
  for (const [index, entry] of targets.entries()) {
    lines.push(`  ${entry.name}${index === targets.length - 1 ? "" : " \\"}`);
  }
  lines.push("");
  lines.push("TASK_SURFACE_HELP_LINES := \\");
  for (const line of helpLines(manifest)) {
    lines.push(`\t'${escapeMakeSingleQuoted(line)}' \\`);
  }
  lines.push("\t''");
  lines.push("");
  if (targetEntryMap(manifest).get("help")?.input_contract?.inputs.some((input) => input.name === "JSON")) {
    lines.push("TASK_SURFACE_HELP_ALL_SELECTED = $(and $(findstring command line,$(origin ALL)),$(filter 1,$(strip $(value ALL))))");
    lines.push("TASK_SURFACE_HELP_JSON_SELECTED = $(and $(findstring command line,$(origin JSON)),$(filter 1,$(strip $(value JSON))))");
  }
  lines.push("TASK_SURFACE_HELP_ALL_LINES := \\");
  for (const line of helpAllLines(manifest)) {
    lines.push(`\t'${escapeMakeSingleQuoted(line)}' \\`);
  }
  lines.push("\t''");
  lines.push("");
  for (const recipe of makeRecipeEntries(manifest).filter((recipe) => recipe.type !== "native_tool")) {
    lines.push(...renderMakeRecipe(recipe, manifest));
    lines.push("");
  }
  lines.push("endif");
  return `${wrapPhysicalLines(lines).join("\n")}\n`;
}

export function renderTaskSurfaceMakeRuntime(manifest, producers = checkoutProducers()) {
  const browserLanes = manifest.targets.flatMap((entry) => entry.input_contract?.inputs ?? []).find((input) => input.name === "BROWSER_LANES");
  const publicInputs = publicMakeInputNames(manifest);
  const literalInputs = literalMakeInputNames(manifest);
  const operationBindings = [...new Set([...operationBindingNames({ operations: Object.fromEntries(
    Object.entries(manifest.make_recipes).filter(([, recipe]) => recipe.operation_id)
      .map(([name, execution]) => [name, { execution }]),
  ) }), ...Object.values(manifest.make_recipes).flatMap((recipe) => recipe.binding_names ?? [])])].filter((name) => !literalInputs.includes(name));
  // Both branches below read the preamble: input defaults and each producer
  // binding's default path.
  const preamble = [
    "# Code generated by tools/harness/generated-artifacts/render-task-surface-make.mjs; DO NOT EDIT.",
    ...(browserLanes ? [`BROWSER_LANES ?= ${browserLanes.default}`] : []),
    ...[...producers.defaults].sort(([left], [right]) => left.localeCompare(right)).map(([binding, file]) => `${binding} ?= $(CURDIR)/${file}`),
  ];
  const lines = [
    ...preamble,
    "",
    "TASK_SURFACE_CANONICAL_TASK_SURFACE_MANIFEST := $(CURDIR)/tools/task_surface_manifest.json",
    "TASK_SURFACE_CANONICAL_SCHEDULER_MANIFEST := $(CURDIR)/tools/scheduler_manifest.json",
    "TASK_SURFACE_CANONICAL_EXECUTION_TOPOLOGY_MANIFEST := $(CURDIR)/tools/execution_topology_manifest.json",
    "",
    "TASK_SURFACE_PUBLIC_INPUT_NAMES := \\",
    ...publicInputs.map(
      (name, index) => `  ${name}${index === publicInputs.length - 1 ? "" : " \\"}`,
    ),
    `TASK_SURFACE_LITERAL_INPUT_NAMES := ${literalInputs.join(" ")}`,
    "unexport $(TASK_SURFACE_LITERAL_INPUT_NAMES)",
    `export ${operationBindings.join(" ")}`,
    "task_surface_shell_quote_raw = '$(subst ','\"'\"',$(value $(1)))'",
    "task_surface_shell_quote_trimmed = '$(subst ','\"'\"',$(strip $(value $(1))))'",
    "TASK_SURFACE_LITERAL_INPUT_ENV = $(foreach name,$(TASK_SURFACE_LITERAL_INPUT_NAMES),$(name)=$(call task_surface_shell_quote_raw,$(name)))",
    "task_surface_input_source = $(if $(findstring command line,$(origin $(1))),cli,$(if $(findstring environment,$(origin $(1))),env,$(if $(filter undefined,$(origin $(1))),unset,file)))",
    "TASK_SURFACE_INPUT_SOURCES = $(foreach name,$(1),$(name)=$(call task_surface_input_source,$(name)))",
    "TASK_SURFACE_COMMAND_LINE_INPUT_NAMES = $(filter-out GNUMAKEFLAGS MAKEFLAGS MFLAGS MAKEOVERRIDES,$(foreach name,$(.VARIABLES),$(if $(findstring command line,$(origin $(name))),$(name))))",
    "TASK_SURFACE_PREFLIGHT_INPUT_NAMES = $(sort $(TASK_SURFACE_PUBLIC_INPUT_NAMES) $(TASK_SURFACE_COMMAND_LINE_INPUT_NAMES))",
    `TASK_SURFACE_MACHINE_STATE_ENV = ${machineStateNames.map((name) => `${name}="$(${name})"`).join(" ")}`,
    // Every managed recipe takes shared workspace admission itself, before
    // any preparation or write; Make parses once (P5-3e).
    "RUN_ADMITTED = bash tools/harness/workspace/admission.sh run --",
    // The command entry admits a public target's inputs, produces its
    // producers and runs it (P5-3e). Make passes what only it knows: each
    // public input's value and origin. The admitted launcher readies Node
    // first: $(2) is install or installed. $(4) names the result envelope a
    // missing or incompatible Node is reported in, when it is not the
    // harness's own.
    'TASK_SURFACE_COMMAND_ENV = $(TASK_SURFACE_LITERAL_INPUT_ENV) CARTULARY_MAKE_INPUT_SOURCES="$(call TASK_SURFACE_INPUT_SOURCES,$(TASK_SURFACE_PREFLIGHT_INPUT_NAMES))" $(TASK_SURFACE_MACHINE_STATE_ENV) MAKE="$(MAKE)" NODE_BIN="$(NODE_BIN)" NODE_RUNTIME_DIR="$(NODE_RUNTIME_DIR)" PNPM="$(PNPM)" GO="$(GO)" RUN_STEP_SCRIPT="$(RUN_STEP_SCRIPT)" TEST_SERVICES_BIN="$(TEST_SERVICES_BIN)" HARNESS_RUNTIME_BIN="$(HARNESS_RUNTIME_BIN)"',
    "TASK_SURFACE_COMMAND_ENTRY = bash tools/harness/command-surface/command-entry.sh",
    "RUN_COMMAND_ENTRY = env $(TASK_SURFACE_COMMAND_ENV) $(3) $(RUN_ADMITTED) $(TASK_SURFACE_COMMAND_ENTRY) $(2) $(1) $(4)",
    "",
  ];
  const nativeRecipes = makeRecipeEntries(manifest).filter((recipe) => recipe.type === "native_tool");
  const nativeInputs = [...new Set(nativeRecipes.flatMap((recipe) => inputEntriesForTarget(targetEntryMap(manifest).get(recipe.target))).concat(globalInputEntries(manifest).map((input) => input.name)))].sort();
  const native = [
    `ifneq ($(filter ${nativeRecipes.map((recipe) => recipe.target).join(" ")},$(MAKECMDGOALS)),)`,
    `TASK_SURFACE_PUBLIC_INPUT_NAMES := ${nativeInputs.join(" ")}`,
    "task_surface_input_source = $(if $(findstring command line,$(origin $(1))),cli,$(if $(findstring environment,$(origin $(1))),env,$(if $(filter undefined,$(origin $(1))),unset,file)))",
    "TASK_SURFACE_INPUT_SOURCES = $(foreach name,$(1),$(name)=$(call task_surface_input_source,$(name)))",
    "TASK_SURFACE_COMMAND_LINE_INPUT_NAMES = $(filter-out GNUMAKEFLAGS MAKEFLAGS MFLAGS MAKEOVERRIDES,$(foreach name,$(.VARIABLES),$(if $(findstring command line,$(origin $(name))),$(name))))",
    "TASK_SURFACE_PREFLIGHT_INPUT_NAMES = $(sort $(TASK_SURFACE_PUBLIC_INPUT_NAMES) $(TASK_SURFACE_COMMAND_LINE_INPUT_NAMES))",
    "TASK_SURFACE_NATIVE_INPUT_SOURCES := $(call TASK_SURFACE_INPUT_SOURCES,$(TASK_SURFACE_PREFLIGHT_INPUT_NAMES))",
    "unexport $(TASK_SURFACE_PUBLIC_INPUT_NAMES)",
    "else", ...lines.slice(preamble.length), "endif",
  ];
  return `${wrapPhysicalLines([...preamble, ...native]).join("\n")}\n`;
}

export function taskSurfaceMakeDensity(manifest, producers = checkoutProducers()) {
  const bindings = renderTaskSurfaceMake(manifest);
  const runtime = renderTaskSurfaceMakeRuntime(manifest, producers);
  const syntheticManifest = structuredClone(manifest);
  for (let index = 1; index <= 25; index += 1) {
    const target = `synthetic-step-target-${String(index).padStart(2, "0")}`;
    syntheticManifest.targets.push({ name: target, target_class: "public", input_contract: { inputs: [] } });
    syntheticManifest.make_recipes[target] = { type: "step_command", mode: "command", command: ["true"] };
  }
  const syntheticBindings = renderTaskSurfaceMake(syntheticManifest);
  return {
    bindings_bytes: Buffer.byteLength(bindings),
    runtime_bytes: Buffer.byteLength(runtime),
    combined_bytes: Buffer.byteLength(bindings) + Buffer.byteLength(runtime),
    maximum_line_bytes: Math.max(maximumLineBytes(bindings), maximumLineBytes(runtime)),
    repeated_origin_transport_count: bindings.split(
      ["CARTULARY", "MAKE", "ORIGIN", ""].join("_"),
    ).length - 1,
    repeated_input_value_expansion_count: (bindings.match(/\$\([A-Z][A-Z0-9_]+\)/g) ?? []).length,
    synthetic_target_count: 25,
    synthetic_average_growth_bytes:
      (Buffer.byteLength(syntheticBindings) - Buffer.byteLength(bindings)) / 25,
  };
}

export function collectTaskSurfaceMakeDensityErrors(manifest, producers = checkoutProducers()) {
  const metrics = taskSurfaceMakeDensity(manifest, producers);
  const errors = [];
  for (const [metric, budget] of [
    ["bindings_bytes", generatedMakeBudgets.bindingsBytes],
    ["runtime_bytes", generatedMakeBudgets.runtimeBytes],
    ["combined_bytes", generatedMakeBudgets.combinedBytes],
    ["maximum_line_bytes", generatedMakeBudgets.maximumLineBytes],
    ["synthetic_average_growth_bytes", generatedMakeBudgets.averageTargetGrowthBytes],
  ]) {
    if (metrics[metric] > budget) {
      errors.push(`generated Make density ${metric}=${metrics[metric]} exceeds budget ${budget}`);
    }
  }
  if (metrics.repeated_origin_transport_count !== 0) {
    errors.push("generated Make bindings must not contain per-variable origin transport");
  }
  return errors;
}

function maximumLineBytes(content) {
  return Math.max(...content.split("\n").map((line) => Buffer.byteLength(line)));
}

// renderMakeRecipe renders one public target as one rule (P5-3e). A target
// that runs through the command entry is one admitted entry call; the UI review
// does too (P6-3). Bootstrap and help first admit their closed selectors, which
// they read before Node exists. The Markdown lint takes admission itself; help,
// cleanup and the read-only run-status tool take none.
function renderMakeRecipe(recipe, manifest) {
  const entry = targetEntryMap(manifest).get(recipe.target);
  if (entry?.target_class !== "public") throw new Error(`${recipe.target}: only a public target has a Make recipe`);
  const family = entryRecipeFamily(recipe, recipe.target);
  if (["graph", "step", "tool", "review"].includes(family)) return [`${recipe.target}:`, renderCommandEntryCall(recipe, entry)];
  if (family === "bootstrap") {
    return [`${recipe.target}:`, renderUndeclaredInputGuard(recipe.target, entry, manifest), ...renderBootstrapSelectorAdmission(entry),
      renderCommandEntryCall(recipe, entry)];
  }
  // Documentation maintenance runs the installed linter directly, outside the
  // harness's preparation, input hashing and retained evidence.
  if (recipe.target === "lint-markdown") return [`${recipe.target}:`, `\t$(Q)$(RUN_ADMITTED) ${recipe.command.join(" ")}`];
  if (recipe.type === "print_help") {
    if (!entry.input_contract?.inputs.some((input) => input.name === "JSON")) throw new Error("help must declare its JSON selector");
    return [`${recipe.target}:`, renderUndeclaredInputGuard(recipe.target, entry, manifest), ...renderBootstrapSelectorAdmission(entry),
      `\t$(Q)case "$\${CARTULARY_OUTPUT_MODE:-summary}" in quiet|summary|ci|verbose|debug) ;; *) echo 'help requires human output mode; use JSON=1 for JSON' >&2; exit 2;; esac`,
      `\t$(Q)$(if $(TASK_SURFACE_HELP_JSON_SELECTED),cat $(if $(TASK_SURFACE_HELP_ALL_SELECTED),tools/task_surface.help-all.generated.json,tools/task_surface.help.generated.json),printf '%s\\n' $(if $(TASK_SURFACE_HELP_ALL_SELECTED),$(TASK_SURFACE_HELP_ALL_LINES),$(TASK_SURFACE_HELP_LINES)))`,
    ];
  }
  // Cleanup takes exclusive admission itself.
  if (recipe.type === "cleanup") {
    return [
      `${recipe.target}: override export CARTULARY_CLEANUP_DRY_RUN := $(value CARTULARY_CLEANUP_DRY_RUN)`,
      `${recipe.target}: override export CARTULARY_OUTPUT_MODE := $(value CARTULARY_OUTPUT_MODE)`,
      `${recipe.target}:`,
      `\t$(Q)CARTULARY_MAKE_COMMAND_LINE_INPUTS="$(TASK_SURFACE_COMMAND_LINE_INPUT_NAMES)" bash ./tools/harness/workspace/cleanup.sh ${recipe.scope}`,
    ];
  }
  if (recipe.type === "native_tool") {
    const tool = nativeTool(recipe.target);
    const inputs = [...new Set([...inputEntriesForTarget(entry), ...globalInputEntries(manifest).map((input) => input.name)])];
    return [`${recipe.target}: SHELL := /bin/sh`,
      ...inputs.map((name) => `${recipe.target}: override export ${name} := $(value ${name})`),
      `${recipe.target}: override export CARTULARY_MAKE_INPUT_SOURCES := $(TASK_SURFACE_NATIVE_INPUT_SOURCES)`,
      `${recipe.target}:`,
      // A simple command lets Make execute the installed owner directly. Missing
      // installations retain the configuration failure without a bootstrap.
      `ifneq ($(wildcard ${tool.binary}),)`,
      `\t$(Q)"${tool.binary}" ${tool.arguments}`,
      "else",
      `\t$(Q)echo "[CONFIG] ${recipe.target} requires the installed diagnostic tool" >&2; exit 2`,
      "endif"];
  }
  throw new Error(`unsupported Make recipe type ${recipe.type}`);
}

// renderCommandEntryCall runs the command entry for recipe under admission.
// Make adds the expanded value of each input the recipe's child receives that
// does not travel literally; TASK_SURFACE_COMMAND_ENV carries the rest. A
// target with a command-line selector, one that asks for it and the UI review
// require the installed Node runtime; bootstrap and every other target install
// it. The UI review reports an unavailable Node in its own result envelope.
function renderCommandEntryCall(recipe, entry) {
  const inputs = new Map((entry?.input_contract?.inputs ?? []).map((input) => [input.name, input]));
  const expanded = entryInputNames(entry, recipe).filter((name) => !requiresLiteralMakeTransport(inputs.get(name)))
    .map((name) => `${name}="${makeVariableValue(name)}"`);
  const review = recipe.type === "ui_review";
  const installed = recipe.type !== "bootstrap" && (review || recipe.runtime_readiness === "installed_only" || entry.selection_binding);
  return `\t$(Q)$(call RUN_COMMAND_ENTRY,${recipe.target},${installed ? "installed" : "install"},${expanded.join(" ")}${review ? ",ui_review" : ""})`;
}

// renderUndeclaredInputGuard refuses a command-line input target does not
// declare, before Node exists.
function renderUndeclaredInputGuard(target, entry, manifest) {
  const names = [...entry.input_contract.inputs.map((input) => input.name), ...globalInputEntries(manifest).map((input) => input.name)];
  return `\t$(Q)$(if $(filter-out ${names.join(" ")},$(TASK_SURFACE_COMMAND_LINE_INPUT_NAMES)),echo '${target} received an undeclared input' >&2; exit 2;,:)`;
}

function inputEntriesForTarget(entry = null) {
  return (entry?.input_contract?.inputs ?? []).map((input) => input.name);
}

function makeVariableValue(name) {
  return canonicalInternalMakeValues[name] ?? `$(${name})`;
}

export function helpLines(manifest) {
  const lines = ["Cartulary compact workflow task surface", ""];
  appendHelpTierLines(lines, {
    name: "compact",
    entries: compactHelpEntries(manifest),
  });
  lines.push("");
  lines.push("For all public commands, run: make help ALL=1");
  lines.push(
    "For exact operation selections, run: make target-plan TARGET=<command> DETAIL=graph",
  );
  return trimTrailingBlank(lines);
}

export function helpAllLines(manifest) {
  const lines = ["Cartulary public task surface", ""];
  lines.push("How to read task evidence:");
  lines.push("  target -> owner partition -> semantic row -> artifact");
  lines.push(
    "  public evidence is runnable from this surface; support/internal evidence is shown by task-guide and explain-*.",
  );
  lines.push("");
  for (const tier of helpTiers(manifest)) {
    appendHelpTierLines(lines, tier);
    lines.push("");
  }
  for (const entry of targetEntries(manifest).filter((value) => value.target_class === "public" && targetEntryMap(manifest).get("help")?.input_contract?.inputs.some((input) => input.name === "JSON"))) {
    lines.push(`${entry.name} inputs: ${(entry.input_contract?.inputs ?? []).map((input) => `${input.name}=${input.values?.join("|") ?? input.type}${input.required ? " (required)" : input.default !== null ? ` (default ${input.default})` : " (optional)"}`).join(", ") || "none"}`);
    lines.push(`  side effects: ${(entry.side_effects ?? []).map((effect) => effect.class).join(", ") || "none"}`);
  }
  return trimTrailingBlank(lines);
}

export function helpProjection(manifest, { all = false } = {}) {
  const compact = new Set(compactHelpEntries(manifest).map((entry) => entry.target));
  return { commands: targetEntries(manifest).filter((entry) => entry.target_class === "public" && (all || compact.has(entry.name)))
    .map((entry) => ({ name: entry.name, command_id: entry.command_id, inputs: entry.input_contract,
      output_policy: entry.output_policy, side_effects: entry.side_effects })) };
}

// Only bootstrap and generated help need admission before a JS runtime exists.
// The allowed values come from the same authored input contracts as JS admission.
export function renderBootstrapSelectorAdmission(entry) {
  return (entry.input_contract?.inputs ?? []).flatMap((input) => {
    if (!["enum", "exact_1_bool"].includes(input.type) || input.allowed_sources.join(",") !== "make_command_line") {
      throw new Error("installation-free selector admission requires closed command-line enums or flags");
    }
    const choices = input.type === "exact_1_bool" ? ["1"] : input.values;
    return [`ifneq ($(findstring command line,$(origin ${input.name})),)`,
      `\t$(Q)case $(call task_surface_shell_quote_trimmed,${input.name}) in ${choices.join("|")}) : ;; *) echo '${input.name} has an invalid value' >&2; exit 2;; esac`,
      ...(input.required ? ["else", `\t$(Q)echo '${input.name} is required' >&2; exit 2`] : []), "endif"];
  });
}

function appendHelpTierLines(lines, tier) {
  if (!tier) {
    return;
  }
  lines.push(`${tier.name}:`);
  for (const entry of tier.entries) {
    lines.push(...renderHelpEntryLines(entry));
  }
}

function renderHelpEntryLines(entry) {
  const command = `make ${entry.target}`;
  const description = entry.description.trim();
  const usage = typeof entry.usage === "string" ? entry.usage.trim() : "";
  if (!usage && entry.target.length <= helpTargetColumnWidth) {
    return [
      `  make ${entry.target.padEnd(helpTargetColumnWidth)} ${description}`,
    ];
  }
  const detail = usage ? `${usage} ${description}` : description;
  return [`  ${command}`, `${helpDescriptionIndent}${detail}`];
}

function trimTrailingBlank(lines) {
  if (lines[lines.length - 1] === "") {
    lines.pop();
  }
  return lines;
}

function escapeMakeSingleQuoted(value) {
  return value.replaceAll("'", "'\"'\"'");
}

function wrapPhysicalLines(lines, maxLength = 500) {
  const wrapped = [];
  for (const line of lines) {
    let remaining = line;
    const continuation = line.startsWith("\t") ? "\t  " : "  ";
    while (remaining.length > maxLength) {
      let split = remaining.lastIndexOf(" ", maxLength - 2);
      if (split <= 0) {
        split = remaining.indexOf(" ", maxLength - 2);
      }
      if (split <= 0) {
        break;
      }
      wrapped.push(`${remaining.slice(0, split)} \\`);
      remaining = `${continuation}${remaining.slice(split + 1)}`;
    }
    wrapped.push(remaining);
  }
  return wrapped;
}
