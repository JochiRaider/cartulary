// TH-HARNESS-REQ-381: host admission charges every resource in the scheduler
// resource registry (TH-HARNESS-REQ-353). One renderer projects that registry
// and the admission state generation into the native and script owners, so no
// hand-maintained admission resource list can drift from the registry.
export const admissionStateGeneration = 3;

const marker = "Code generated by tools/harness/generated-artifacts/admission-vocabulary.mjs; DO NOT EDIT.";

export function admissionResources(registry) {
  const names = registry.resources.map((resource) => resource.name);
  if (names.length === 0 || names.some((name) => !/^[a-z][a-z0-9_]*$/u.test(name)) ||
      JSON.stringify(names) !== JSON.stringify([...new Set(names)].sort())) {
    throw new Error("scheduler resource registry names must be unique, sorted lower-case identifiers");
  }
  return names;
}

export function renderAdmissionVocabulary(registry) {
  const names = admissionResources(registry);
  const go = `// ${marker}

//go:build linux

package harnessadmission

// resources is the host admission vocabulary: every scheduler registry resource.
var resources = []string{${names.map((name) => JSON.stringify(name)).join(", ")}}

// stateGeneration versions the on-disk admission state and names its root, so a
// binary of another generation never reads or rewrites this state.
const stateGeneration = ${admissionStateGeneration}
`;
  const js = `// ${marker}
export const admissionResources = Object.freeze(${JSON.stringify(names)});
export const admissionStateGeneration = ${admissionStateGeneration};
`;
  return { go, js };
}
