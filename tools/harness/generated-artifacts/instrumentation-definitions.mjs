import { instrumentationShapes as shapes } from "./instrumentation-shapes.mjs";

const marker = "Code generated by tools/harness/generated-artifacts/generate-foundation-schema-validators.mjs; DO NOT EDIT.";

export function renderInstrumentationDefinitions(catalog) {
  const names = new Set();
  for (const signal of catalog.signals) {
    if (names.has(signal.name)) throw new Error("duplicate instrumentation signal");
    names.add(signal.name);
    if (signal.aggregation !== (signal.kind === "counter" ? "segmented_delta" : "sampled_maximum")) throw new Error("inconsistent instrumentation aggregation");
  }
  const properties = (name) => Object.fromEntries(catalog.signals.map((signal) => [signal.name, { $ref: `#/$defs/${name}` }]));
  const schema = {
    $schema: "https://json-schema.org/draft/2020-12/schema",
    $id: "cartulary.harness_instrumentation_defs.v1", $comment: marker,
    $defs: {
      ...structuredClone(shapes),
      availability: { enum: catalog.availability }, phase: { enum: catalog.phases },
      phase_union: { type: "object", additionalProperties: false, required: [],
        properties: Object.fromEntries(catalog.phases.map((phase) => [phase, { type: "integer", minimum: 0 }])) },
      sample_metrics: { type: "object", additionalProperties: false, properties: properties("sample_value") },
      aggregate_metrics: { type: "object", additionalProperties: false, required: [], properties: properties("aggregate_value") },
    },
  };
  const runtime = `// ${marker}\n` +
    `export const maximumPhasesPerUnit = ${catalog.maximum_phases_per_unit};\n` +
    `export const phases = Object.freeze(${JSON.stringify(catalog.phases)});\n` +
    `export const signals = Object.freeze(${JSON.stringify(Object.fromEntries(catalog.signals.map(({ name, ...signal }) => [name, signal])))});\n`;
  return { schema, runtime };
}
