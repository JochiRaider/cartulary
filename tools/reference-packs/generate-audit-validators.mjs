// Producer schemas remain with their independent modules. This tooling-only
// projection has no installed-package dependency at audit execution time.
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import path from "node:path";
import { compileStandaloneValidators, validatorFilename } from "../harness/generated-artifacts/schema-validator-compiler.mjs";
import { publishGeneratedTransaction } from "../harness/generated-artifacts/generated-transaction.mjs";

const root = process.cwd();
const contracts = JSON.parse(readFileSync("tools/reference-packs/audit-contracts.json"));
const schemas = Object.values(contracts).map(contract => {
  const schema = JSON.parse(readFileSync(contract.schema));
  if (contract.fragment) return { ...schema, $id: contract.schema_id, $ref: contract.fragment };
  if (schema.$id !== contract.schema_id) throw new Error("audit schema identity mismatch");
  return schema;
});
const output = "tools/reference-packs/generated";
mkdirSync("tmp", {recursive: true});
const scratch = mkdtempSync(path.join(root, "tmp/audit-validators-"));
try {
  mkdirSync(path.join(scratch, output), {recursive: true});
  for (const [id, source] of compileStandaloneValidators(schemas)) {
    writeFileSync(path.join(scratch, output, validatorFilename(id)), `// Code generated by tools/reference-packs/generate-audit-validators.mjs; DO NOT EDIT.\n${source}\n`);
  }
  publishGeneratedTransaction({repoRoot: root, renderedRoot: scratch, generatedPaths: [output]});
} finally { rmSync(scratch, {recursive: true, force: true}); }
