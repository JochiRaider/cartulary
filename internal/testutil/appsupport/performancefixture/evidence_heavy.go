// This is the application's typed projection of the fixture portion of the
// authored contract. Runtime reads generated bytes, never repository documents.
type evidenceHeavyWorkload struct {
	FixtureID           string `json:"fixture_id"`
	Seed                int    `json:"seed"`
	TimelineRows        int    `json:"timeline_rows"`
	EvidenceRows        int    `json:"evidence_rows"`
	ObjectCount         int    `json:"object_count"`
	ObjectBytes         int    `json:"object_bytes"`
	TotalObjectBytes    int64  `json:"total_object_bytes"`
	TitlePrefix         string `json:"evidence_title_prefix"`
	TargetSummary       string `json:"target_summary"`
	LinkedEvidenceCount int    `json:"linked_evidence_count"`
	AnalystSessions     int    `json:"analyst_sessions"`
}

func evidenceHeavyContract(profile performancefixtureprofile.Profile) (evidenceHeavyWorkload, error) {
	artifact, ok := contractperformance.Index["contracts/performance/ac045.v2.json"]
	if !ok {
		return evidenceHeavyWorkload{}, errors.New("evidence inspector contract projection is unavailable")
	}
	var document struct {
		SchemaID   string                `json:"schema_id"`
		ContractID string                `json:"contract_id"`
		Fixture    evidenceHeavyWorkload `json:"fixture"`
	}
	if err := json.Unmarshal([]byte(artifact.JSON), &document); err != nil {
		return evidenceHeavyWorkload{}, err
	}
	w := document.Fixture
	bound := false
	for _, ref := range profile.SourceContractRefs {
		if ref.SchemaID == document.SchemaID && ref.ContractID == document.ContractID {
			bound = true
		}
	}
	if document.SchemaID != "cartulary.performance_evidence_inspector_contract.v1" || document.ContractID != "cartulary.performance.ac045.v2" || !bound ||
		profile.FixtureVersion != w.FixtureID || profile.Seed != w.Seed ||
		profile.ObjectPopulation.ObjectCount != w.ObjectCount || profile.ObjectPopulation.TotalBytes != w.TotalObjectBytes ||
		w.TimelineRows < 2 || w.EvidenceRows < 1 || w.EvidenceRows > 10000 || w.LinkedEvidenceCount < 65 || w.LinkedEvidenceCount > 100 || w.LinkedEvidenceCount > w.EvidenceRows ||
		w.ObjectBytes < 256 || w.ObjectBytes > 2*1024*1024 || w.AnalystSessions != 1 || w.TargetSummary == "" || w.TitlePrefix == "" ||
		w.ObjectCount != w.EvidenceRows || int64(w.ObjectCount)*int64(w.ObjectBytes) != w.TotalObjectBytes ||
		len(profile.RuntimeCredentialSets) != 1 || profile.RuntimeCredentialSets[0].SetID != "foreground_analysts" ||
		profile.RuntimeCredentialSets[0].CredentialKind != "email_password" || profile.RuntimeCredentialSets[0].AccountCount != w.AnalystSessions {
		return evidenceHeavyWorkload{}, errors.New("evidence inspector profile differs from its exact workload")
	}
	return w, nil
}

func newEvidenceHeavyProduction(pool postgres.DB, actor authn.UserRecord, profile performancefixtureprofile.Profile, owners *Owners) (*fixture.Assembler, error) {
	workload, err := evidenceHeavyContract(profile)
	if err != nil {
		return nil, err
	}
	descriptors, err := fixture.Descriptors(profile)
	if err != nil {
		return nil, err
	}
	if len(descriptors) != 6 {
		return nil, errors.New("evidence inspector requires exactly six owner contributions")
	}
	byOwner := map[string]fixture.Descriptor{}
	for _, descriptor := range descriptors {
		if _, duplicate := byOwner[descriptor.OwnerID]; duplicate {
			return nil, errors.New("duplicate Evidence inspector owner contribution")
		}
		byOwner[descriptor.OwnerID] = descriptor
	}
	expected := map[string]map[string]int{
		"module.auth":          {"accounts": workload.AnalystSessions, "sessions": 0},
		"module.incidents":     {"incidents": 1, "workspaces": 1, "memberships": workload.AnalystSessions},
		"module.evidence":      {"evidence_records": workload.EvidenceRows, "object_blobs": workload.ObjectCount, "total_object_bytes": int(workload.TotalObjectBytes)},
		"module.timeline":      {"timeline_rows": workload.TimelineRows, "attached_evidence": workload.LinkedEvidenceCount},
		"module.projections":   {"projection_sets": 2},
		"module.collaboration": {"pending_intents": 0},
	}
	for owner, counts := range expected {
		if !maps.Equal(byOwner[owner].ExpectedCounts, counts) {
			return nil, fmt.Errorf("evidence inspector contribution %s has incompatible population", owner)
		}
	}
	authApplication, err := authfixture.NewProductionApplication(pool, actor)
	if err != nil {
		return nil, err
	}
	auth, err := authfixture.New(authApplication, byOwner["module.auth"], "foreground_analysts", "Performance Analyst")
	if err != nil {
		return nil, err
	}
	incidentApplication, err := incidentsfixture.NewProductionApplication(pool, actor)
	if err != nil {
		return nil, err
	}
	incidents, err := incidentsfixture.New(incidentApplication, byOwner["module.incidents"], incidentsfixture.WorkspaceIdentity{KeyPrefix: "AC045-PERF", Title: "Evidence-heavy performance fixture"})
	if err != nil {
		return nil, err
	}
	evidence, err := evidencefixture.New(owners.Evidence, actor.ID, byOwner["module.evidence"], workload.ObjectBytes, workload.TitlePrefix)
	if err != nil {
		return nil, err
	}
	timelineApplication, err := timelinefixture.NewEvidenceInspectorApplication(owners.Timeline, owners.TimelineMutations, actor)
	if err != nil {
		return nil, err
	}
	timeline, err := timelinefixture.NewInspectorProvider(timelineApplication, evidence, byOwner["module.timeline"])
	if err != nil {
		return nil, err
	}
	projectionApplication, err := projectionsfixture.NewProductionApplication(owners.Projections)
	if err != nil {
		return nil, err
	}
	projections, err := projectionsfixture.New(projectionApplication, byOwner["module.projections"], []projectionsfixture.SetExpectation{
		{ViewSchemaID: "cartulary.view.evidence.v1", ExactRows: workload.EvidenceRows},
		{ViewSchemaID: "cartulary.view.timeline.v2", ExactRows: workload.TimelineRows},
	})
	if err != nil {
		return nil, err
	}
	publications, err := collaborationfixture.New(pool, byOwner["module.collaboration"])
	if err != nil {
		return nil, err
	}
	return fixture.NewAssembler(profile, &evidenceHeavyValidator{pool: pool, workload: workload, evidence: evidence, timeline: timeline}, auth, incidents, evidence, timeline, projections, publications)
}

type evidenceHeavyValidator struct {
	pool     postgres.DB
	workload evidenceHeavyWorkload
	evidence *evidencefixture.Provider
	timeline *timelinefixture.InspectorProvider
}

func (v *evidenceHeavyValidator) Validate(ctx context.Context, state *fixture.BuildState) (fixture.SemanticValidation, error) {
	if state == nil || v.evidence == nil || v.timeline == nil {
		return fixture.SemanticValidation{}, errors.New("evidence inspector validation requires constructed owners and state")
	}
	incidentID, err := uuid.Parse(state.IncidentID)
	if err != nil {
		return fixture.SemanticValidation{}, err
	}
	target := v.timeline.Target()
	ids := v.evidence.RecordIDs()
	if target.RecordID == uuid.Nil || target.Summary != v.workload.TargetSummary || target.RowVersion != 2 || len(ids) != v.workload.EvidenceRows || v.workload.LinkedEvidenceCount < 1 || v.workload.LinkedEvidenceCount > len(ids) {
		return fixture.SemanticValidation{}, errors.New("evidence inspector owner bindings diverged")
	}
	linkedIDs := ids[:v.workload.LinkedEvidenceCount]
	counts := map[string]int{}
	for key, query := range map[string]string{
		"timeline_rows":      `SELECT COUNT(*) FROM timeline_events WHERE incident_id=$1`,
		"evidence_rows":      `SELECT COUNT(*) FROM evidence WHERE incident_id=$1`,
		"object_blobs":       `SELECT COUNT(*) FROM object_blobs WHERE incident_id=$1`,
		"total_object_bytes": `SELECT COALESCE(SUM(byte_size),0) FROM object_blobs WHERE incident_id=$1`,
		"attached_evidence":  `SELECT COUNT(*) FROM record_links WHERE incident_id=$1 AND link_type='attached_evidence' AND field_key='timeline.attached_evidence_ids' AND deleted_at IS NULL`,
		"analyst_accounts":   `SELECT COUNT(*) FROM incident_memberships m JOIN users u ON u.id=m.user_id WHERE m.incident_id=$1 AND m.role='editor' AND u.is_active AND NOT u.is_deployment_admin AND NOT u.mfa_required`,
	} {
		var count int
		if err := v.pool.QueryRow(ctx, query, incidentID).Scan(&count); err != nil {
			return fixture.SemanticValidation{}, fmt.Errorf("query Evidence inspector %s: %w", key, err)
		}
		counts[key] = count
	}
	var sessions, handles, uploadLeases, defaultViews, exactLinks, exactTarget, exactEvidence int
	if err := v.pool.QueryRow(ctx, `SELECT COUNT(*) FROM user_sessions WHERE revoked_at IS NULL`).Scan(&sessions); err != nil {
		return fixture.SemanticValidation{}, err
	}
	counts["active_sessions"] = sessions
	var pending, quarantined, missingReplay int
	if err := v.pool.QueryRow(ctx, `SELECT
 (SELECT COUNT(*) FROM collaboration_event_intents WHERE dispatch_state<>'sequenced'),
 (SELECT COUNT(*) FROM collaboration_incident_stream_cursors WHERE quarantined_at IS NOT NULL),
 (SELECT COUNT(*) FROM collaboration_event_intents i LEFT JOIN collaboration_replay_events r ON r.event_id=i.sequenced_event_id
   AND r.incident_id=i.incident_id AND r.intent_key=i.intent_key AND r.event_family=i.event_family AND r.canonical_payload=i.canonical_payload
   WHERE r.event_id IS NULL)`).Scan(&pending, &quarantined, &missingReplay); err != nil {
		return fixture.SemanticValidation{}, err
	}
	counts["pending_publication_intents"] = pending
	for _, query := range []struct {
		sql    string
		result *int
	}{
		{`SELECT COUNT(*) FROM evidence_access_handles WHERE incident_id=$1`, &handles},
		{`SELECT COUNT(*) FROM evidence_object_upload_leases WHERE incident_id=$1`, &uploadLeases},
		{`SELECT COUNT(*) FROM incident_workbook_preferences WHERE incident_id=$1 AND default_sheet_ref IS NULL`, &defaultViews},
	} {
		if err := v.pool.QueryRow(ctx, query.sql, incidentID).Scan(query.result); err != nil {
			return fixture.SemanticValidation{}, err
		}
	}
	if err := v.pool.QueryRow(ctx, `SELECT COUNT(*) FROM record_links WHERE incident_id=$1 AND src_record_id=$2 AND dst_record_id=ANY($3::uuid[]) AND link_type='attached_evidence' AND field_key='timeline.attached_evidence_ids' AND deleted_at IS NULL`, incidentID, target.RecordID, linkedIDs).Scan(&exactLinks); err != nil {
		return fixture.SemanticValidation{}, err
	}
	if err := v.pool.QueryRow(ctx, `SELECT COUNT(*) FROM timeline_grid_projection p JOIN records r USING(record_id) WHERE p.incident_id=$1 AND p.record_id=$2 AND p.row_version=$3 AND r.row_version=$3 AND p.activity_synopsis_text=$4 AND p.evidence_count=$5 AND p.has_evidence AND jsonb_array_length(p.attached_evidence_refs)=$5`, incidentID, target.RecordID, target.RowVersion, target.Summary, v.workload.LinkedEvidenceCount).Scan(&exactTarget); err != nil {
		return fixture.SemanticValidation{}, err
	}
	payload, err := evidencefixture.ImagePayload(v.workload.ObjectBytes)
	if err != nil {
		return fixture.SemanticValidation{}, err
	}
	digest := sha256.Sum256(payload)
	if err := v.pool.QueryRow(ctx, `SELECT COUNT(*) FROM evidence e JOIN records r USING(record_id) JOIN object_blobs b ON b.object_blob_id=e.object_blob_id JOIN evidence_grid_projection p ON p.record_id=e.record_id
 WHERE e.incident_id=$1 AND e.record_id=ANY($2::uuid[]) AND r.deleted_at IS NULL AND r.row_version=1 AND p.row_version=1
 AND e.lifecycle_state='available' AND p.lifecycle_state='available' AND b.upload_state='available' AND p.upload_state='available'
 AND b.byte_size=$3 AND b.observed_size=$3 AND b.observed_content_type='image/png' AND b.observed_sha256_hex=$4 AND b.expected_sha256_hex=$4
 AND p.title=e.title AND p.blob_hash=$4 AND p.linked_record_count=CASE WHEN e.record_id=ANY($5::uuid[]) THEN 1 ELSE 0 END`, incidentID, ids, v.workload.ObjectBytes, hex.EncodeToString(digest[:]), linkedIDs).Scan(&exactEvidence); err != nil {
		return fixture.SemanticValidation{}, err
	}
	return fixture.SemanticValidation{Counts: counts, Conditions: map[string]bool{
		"authorization":                       counts["analyst_accounts"] == v.workload.AnalystSessions && len(state.PrincipalUserIDs) == v.workload.AnalystSessions,
		"default_view":                        defaultViews == 1,
		"no_active_sessions":                  sessions == 0,
		"no_access_handles_or_upload_leases":  handles == 0 && uploadLeases == 0,
		"target_binding":                      exactTarget == 1 && exactLinks == v.workload.LinkedEvidenceCount,
		"projection_ready":                    exactEvidence == v.workload.EvidenceRows && exactTarget == 1,
		"construction_publications_sequenced": pending == 0 && quarantined == 0 && missingReplay == 0,
	}}, nil
}
