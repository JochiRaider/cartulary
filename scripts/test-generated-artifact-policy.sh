cartulary_filter_authored_go_packages
EOF
  cat >"$repo/tools/harness/static-analysis/go-govulncheck.sh" <<'EOF'
source tools/harness/generated-artifacts/generated-artifacts.sh
cartulary_filter_authored_go_packages
EOF
  cat >"$repo/tools/harness/static-analysis/shellcheck.sh" <<'EOF'
source tools/harness/generated-artifacts/generated-artifacts.sh
cartulary_is_generated_artifact_path
EOF
  cat >"$repo/biome.json" <<'JSON'
{
  "files": {
    "includes": [
      "packages/protocol-ts/src/**",
      "!packages/protocol-ts/src/generated/**",
      "packages/ui-contracts/src/**",
      "!packages/ui-contracts/src/generated/**"
    ]
  },
  "overrides": [
    {
      "includes": [
        "packages/protocol-ts/src/**",
        "!packages/protocol-ts/src/generated/**",
        "packages/ui-contracts/src/**",
        "!packages/ui-contracts/src/generated/**"
      ]
    }
  ]
}
JSON
  cat >"$repo/tools/frontend_import_boundaries.json" <<'JSON'
{
  "schema_id": "cartulary.frontend_import_boundaries.v2",
  "scan_excludes": [
    "packages/protocol-ts/src/generated/**",
    "packages/ui-contracts/src/generated/**"
  ],
  "rules": [
    {
      "id": "frontend-generated-protocol-boundary",
      "restricted_imports": [
        {
          "kind": "path_prefix",
          "path": "packages/protocol-ts/src/generated"
        }
      ]
    },
    {
      "id": "frontend-generated-design-token-boundary",
      "restricted_imports": [
        {
          "kind": "path_prefix",
          "path": "packages/ui-contracts/src/generated"
        }
      ]
    }
  ]
