write_support_files() {
  local repo="$1"
  mkdir -p \
    "$repo/internal/gen/contracts" \
    "$repo/packages/protocol-ts/src/generated" \
    "$repo/packages/ui-contracts/src/generated" \
    "$repo/tools/harness/generated-artifacts" \
    "$repo/tools/harness/static-analysis"

  printf '%s\n' '// Code generated by test; DO NOT EDIT.' 'package contracts' >"$repo/internal/gen/contracts/contracts_gen.go"
  printf '%s\n' '// Code generated by test; DO NOT EDIT.' 'export const value = 1;' >"$repo/packages/protocol-ts/src/generated/contracts.ts"
  printf '%s\n' '// Code generated by test; DO NOT EDIT.' 'export const designTokens = {};' >"$repo/packages/ui-contracts/src/generated/design-tokens.ts"
  printf '%s\n' '# Code generated by test; DO NOT EDIT.' '.PHONY: help' >"$repo/tools/task_surface.generated.mk"
  : >"$repo/internal/gen/contracts/.gitkeep"
  : >"$repo/packages/protocol-ts/src/generated/.gitkeep"
  : >"$repo/packages/ui-contracts/src/generated/.gitkeep"
  cat >"$repo/tools/harness/generated-artifacts/generated-artifacts.sh" <<'EOF'
cartulary_is_authored_go_file() { :; }
cartulary_filter_authored_go_packages() { :; }
cartulary_is_generated_artifact_path() { :; }
EOF
  cat >"$repo/tools/harness/static-analysis/go-format.sh" <<'EOF'
source tools/harness/generated-artifacts/generated-artifacts.sh
cartulary_is_authored_go_file
EOF
  cat >"$repo/tools/harness/static-analysis/go-vet.sh" <<'EOF'
source tools/harness/generated-artifacts/generated-artifacts.sh
cartulary_filter_authored_go_packages
EOF
  cat >"$repo/tools/harness/static-analysis/go-staticcheck.sh" <<'EOF'
